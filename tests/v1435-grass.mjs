import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const ver = JSON.parse(fs.readFileSync(path.join(root, 'version.json'), 'utf8'));
let n = 0;
const ok = (c, l) => { assert.ok(c, l); console.log('ok ' + (++n) + ' ' + l); };
ok(html.includes("const GAME_VERSION = '" + ver.v + "';"), 'GAME_VERSION matches version.json');
ok(html.includes('GLX-GRASS1435') && html.includes('WIN.__noGrass1435'), '3D grass is inlined with an off switch (__noGrass1435)');
ok(html.includes('(function tufts()') && html.includes('window.__c81tuft = im'), 'old C81 cross-quad tufts are still in the file');
ok(html.includes('__c81tuft.layers.set(30)') && html.includes('__c81tuft.layers.set(0)'), 'old tufts are hidden while on and restored when off');
ok(html.includes('texImg.grass_side') && html.includes('TONES = [pick('), 'blade colours come from the grass block side turf');
ok(html.includes('uCam') && html.includes("'float dC = distance(o.xz, uCam.xz);',"), 'distance fade uses its own camera uniform (Basic material gets no cameraPosition)');
ok(/gust/.test(html) && html.includes('uWind') && html.includes('push'), 'vertex-shader wind and foot push');
ok(html.includes('g1435t') && html.includes('uG1435'), 'old tall-grass quads are hidden only inside the 3D ring');
ok(html.includes('SET.noFoliage') && html.includes('ck < 0.85 && !nofol'), 'respects Disable foliage and hides in caves');
const m = html.match(new RegExp('"v":"v' + ver.v.replace(/\./g, '\\.') + '","d":"[^"]+","notes":(\\[[^\\]]+\\])'));
ok(m && /3D grass|grass/i.test(m[1]), 'patch notes lead with the 3D grass');
ok(m && !/\b(food|hungry|eat|eaten|meal|dinner|lunch|breakfast|haggis|tatties|neeps)\b/i.test(m[1]), 'no food words in the notes');
console.log('PASS ' + n + '/' + n);
