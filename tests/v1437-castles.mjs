import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const ver = JSON.parse(fs.readFileSync(path.join(root, 'version.json'), 'utf8'));
let n = 0;
const ok = (c, l) => { assert.ok(c, l); console.log('ok ' + (++n) + ' ' + l); };
ok(ver.v === '1.2.154' || ver.v >= '1.2.154', 'version is 1.2.154+');
ok(html.includes("const GAME_VERSION = '" + ver.v + "';"), 'GAME_VERSION matches version.json');
ok(html.includes('GLX-CASTLE1437') && html.includes('window.__noCastle1437'), 'castle dress is inlined with an off switch');
ok(html.includes('dressHuman') && html.includes('dressMossy') && html.includes('dressBlack') && html.includes('dressSpawn'), 'clan, ruin, black and spawn hill dressers are present');
ok(html.includes('portcullis') && html.includes('tartan') && html.includes('T.HEATHER') && html.includes('T.LAVA') && html.includes('T.COBWEB'), 'dress adds portcullis, tartan, heather, lava and cobwebs');
ok(html.includes('C.work.__c1437') && html.includes('G.hook.__c1437'), 'hooks the existing C151 work and GB6 off-grid hook, originals kept');
ok(html.includes('current.c1437') && html.includes('save.c1437') && html.includes('d.c1437 = 1'), 'only new or Reset worlds are dressed; the flag is saved');
ok(html.includes('U.B.human') && html.includes('designBlack') && html.includes('GLX-C151') && html.includes('GLX-GB6'), 'original castle builders are still in the file');
ok(html.includes('"v":"v1.2.154"') && /spires|portcullis|tartan|crag|lava|pines/i.test(html), 'patch notes lead with the castle dress');
const notes = html.match(/"v":"v1.2.154","d":"[^"]+","notes":(\[[^\]]+\])/);
ok(notes && !/\b(food|hungry|eat|eaten|meal|dinner|lunch|breakfast|haggis|tatties|neeps)\b/i.test(notes[1]), 'no food words in the notes');
ok(html.includes('castleBuilt') && html.includes('spawnReady') && html.includes('hookGenerate'), 'dress also runs when castle chunks are built, not only at genDone / closed-over C151.work');
console.log('PASS ' + n + '/' + n);
