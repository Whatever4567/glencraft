#!/usr/bin/env python3
"""Build the three upscaled explorable castle models, pack RLE, render previews."""
from __future__ import annotations
import sys, json, time, zlib, base64, struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # repo root
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from clansman import build_clansman
from ruin import build_ruin
from vox import pack_rle
from render_sil import render, iou
from PIL import Image, ImageDraw, ImageFont
import numpy as np

OUT_ASSETS = ROOT / 'assets' / 'castles'
OUT_SRC = ROOT / 'tools' / 'content-source'
OUT_QA = Path('/workspace/qa/castles/v3')
for d in (OUT_ASSETS, OUT_SRC, OUT_QA / 'models', OUT_QA / 'renders'):
    d.mkdir(parents=True, exist_ok=True)


def specials_jsonable(spec):
    out = {}
    for k, v in spec.items():
        rows = []
        for item in v:
            row = {}
            for kk, vv in item.items():
                if isinstance(vv, (int, float, str, bool)) or vv is None:
                    row[kk] = vv
                else:
                    row[kk] = str(vv)
            rows.append(row)
        out[k] = rows
    return out


def write_js(models, path):
    parts = ['// generated by tools/castles/build_models.py — do not edit\n',
             'window.__castleModels = {\n']
    for name, m in models.items():
        comp = base64.b64encode(zlib.compress(m['raw'], 9)).decode('ascii')
        wrapped = '\n    '.join(comp[i:i + 120] for i in range(0, len(comp), 120))
        spec = json.dumps(m['specials'], separators=(',', ':'))
        stats = json.dumps(m['stats'], separators=(',', ':'))
        parts.append(f'  "{name}": {{\n    z: "\\\n    {wrapped}",\n    s: {spec},\n    n: {stats}\n  }},\n')
    parts.append('};\n')
    path.write_text(''.join(parts))


def hero_cam(specials, fallback):
    for c in specials.get('camera', []):
        if c.get('name') == 'hero':
            return (c['x'], c['y'], c['z']), (c['lx'], c['ly'], c['lz']), c.get('fov', 52)
    return fallback


def main():
    t0 = time.time()
    builders = {
        'clansman': build_clansman,
        'skeleton': lambda: build_ruin('mossy'),
        'black-skeleton': lambda: build_ruin('black'),
    }
    models = {}
    for name, fn in builders.items():
        t1 = time.time()
        print(f'building {name}...', flush=True)
        g = fn()
        raw, spec, stats = pack_rle(g)
        spec = specials_jsonable(spec)
        dt = time.time() - t1
        print(f'  blocks={stats["blocks"]} runs={stats["runs"]} aabb={stats["aabb"]} pack={len(raw)}B  {dt:.1f}s', flush=True)
        bin_path = OUT_ASSETS / f'{name}.bin'
        js = json.dumps({'specials': spec, 'stats': stats}, separators=(',', ':')).encode('utf-8')
        bin_path.write_bytes(raw + js + struct.pack('<I', len(js)) + b'JS13')
        (OUT_QA / 'models' / f'{name}.json').write_text(json.dumps({'stats': stats, 'specials': spec}, indent=2))
        models[name] = {'raw': raw, 'specials': spec, 'stats': stats, 'grid': g}

    write_js(models, OUT_SRC / 'castle-models-1313.js')
    print('wrote', OUT_SRC / 'castle-models-1313.js',
          'bytes', (OUT_SRC / 'castle-models-1313.js').stat().st_size)

    # offline renders at the hero camera (first iteration)
    for name, m in models.items():
        eye, look, fov = hero_cam(m['specials'], ((18, 16, 64), (4, 36, 8), 52))
        print(f'rendering {name} eye={eye} look={look} fov={fov}...', flush=True)
        t1 = time.time()
        img, mask = render(m['grid'].iter_blocks(), eye, look, fov=fov, w=960, h=540)
        Image.fromarray(img).save(OUT_QA / 'renders' / f'{name}-model.png')
        Image.fromarray(mask * 255).save(OUT_QA / 'renders' / f'{name}-model-mask.png')
        print(f'  render {time.time()-t1:.1f}s  mask frac={mask.mean():.3f}', flush=True)

    print(f'done in {time.time()-t0:.1f}s')


if __name__ == '__main__':
    main()
